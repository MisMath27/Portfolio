let currentLang = 'en';

function translatePage(lang) {
    currentLang = lang;

    document.querySelectorAll('.translate-dropdown button').forEach(btn => {
        btn.classList.remove('active-lang');
        if (btn.dataset.lang === lang) {
            btn.classList.add('active-lang');
        }
    });

    const textElements = document.querySelectorAll(
        'h2, h3, p, li, .developer-title, .block-description, ' +
        '.info-list li, .additional-list li, .btn-text'
    );

    textElements.forEach(element => {
        if (!element.hasAttribute('data-original')) {
            element.setAttribute('data-original', element.textContent.trim());
        }

        const originalText = element.getAttribute('data-original');
        const translated = translations[lang]?.[originalText];

        if (translated) {
            element.textContent = translated;
        }
    });


    const btnText = document.querySelector('.btn-text');
    if (btnText) {
        const originalBtnText = btnText.getAttribute('data-original') || 'Перевести';
        btnText.setAttribute('data-original', originalBtnText);
        const translatedBtn = translations[lang]?.[originalBtnText];
        if (translatedBtn) {
            btnText.textContent = translatedBtn;
        }
    }


    const menuLabel = document.querySelector('.menu-label');
    if (menuLabel) {
        const originalLabel = menuLabel.getAttribute('data-original') || 'Выберите язык';
        menuLabel.setAttribute('data-original', originalLabel);
        const translatedLabel = translations[lang]?.[originalLabel];
        if (translatedLabel) {
            menuLabel.textContent = translatedLabel;
        }
    }


    document.querySelectorAll('.translate-dropdown button').forEach(btn => {
        const langName = btn.querySelector('.lang-name');
        if (langName) {
            const originalName = langName.getAttribute('data-original') || langName.textContent;
            langName.setAttribute('data-original', originalName);
            const translatedName = translations[lang]?.[originalName];
            if (translatedName) {
                langName.textContent = translatedName;
            }
        }
    });


    closeDropdown();
}

function toggleDropdown() {
    const dropdown = document.getElementById('translateDropdown');
    const arrow = document.getElementById('arrowIcon');

    if (dropdown.classList.contains('active')) {
        closeDropdown();
    } else {
        dropdown.classList.add('active');
        arrow.classList.add('open');
    }
}

function closeDropdown() {
    const dropdown = document.getElementById('translateDropdown');
    const arrow = document.getElementById('arrowIcon');
    dropdown.classList.remove('active');
    arrow.classList.remove('open');
}


document.addEventListener('click', function(event) {
    const wrapper = document.querySelector('.translate-wrapper');
    if (wrapper && !wrapper.contains(event.target)) {
        closeDropdown();
    }
});


document.addEventListener('DOMContentLoaded', function() {
    const textElements = document.querySelectorAll(
        'h2, h3, p, li, .developer-title, .block-description, ' +
        '.info-list li, .additional-list li, .btn-text, .menu-label, .lang-name'
    );

    textElements.forEach(element => {
        if (!element.hasAttribute('data-original')) {
            element.setAttribute('data-original', element.textContent.trim());
        }
    });
});